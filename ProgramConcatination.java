class ProgramConcatination
{
  public static void main(String[] args)
  {
   System.out.println("Qspider" + "Jspider");
   System.out.println("Boys " + 90);
   System.out.println(143 +"Students");
   System.out.println("10" + 10);
   System.out.println(10 + "10");
   System.out.println("A"+ 10);
   System.out.println('A' + 10);
   System.out.println("Done Concatination");
  }
}